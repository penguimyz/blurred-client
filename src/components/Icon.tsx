/** Turn a grid into a single path of 1x1 squares, merging horizontal runs. */
function gridToPath(rows: string[]): string {
  let d = "";
  for (let y = 0; y < rows.length; y++) {
    const row = rows[y];
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      // Extend across the run so a solid row is one rect, not twelve.
      let run = 1;
      while (x + run < row.length && row[x + run] === "#") run++;
      d += `M${x} ${y}h${run}v1h-${run}z`;
      x += run;
    }
  }
  return d;
}

// Built once at module load — the grids never change, so re-deriving a path on
// every render would be pure waste.
const PATHS: Record<string, string> = Object.fromEntries(
  Object.entries(ICONS).map(([name, rows]) => [name, gridToPath(rows)])
);

interface IconProps {
  name: IconName;
  size?: number;
  style?: CSSProperties;
  className?: string;
  /** Decorative by default; pass a label when the icon is the only content. */
  label?: string;
}

export function Icon({ name, size = 18, style, className, label }: IconProps) {
  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${G} ${G}`}
      fill="currentColor"
      shapeRendering="crispEdges"
      className={className}
      style={{ flexShrink: 0, ...style }}
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
    >
      <path d={PATHS[name]} />
    </svg>
  );
}

/**
 * The app mark: a porthole in two tones. Same grid format, but with a second
 * character (`o`) for the accent-coloured waterline, so it reads as a logo
 * rather than another nav icon.
 */
// prettier-ignore
const LOGO_ROWS = [
  "....####....",
  "..##....##..",
  ".#........#.",
  "#..........#",
  "#..........#",
  "#..oo....oo#",
  "#.o..oooo..o",
  "#..........#",
  ".#........#.",
  "..##....##..",
  "....####....",
  "............",
];

export function Logo({ size = 18 }: { size?: number }) {
  const ring = gridToPath(LOGO_ROWS);
  const water = gridToPath(LOGO_ROWS.map((r) => r.replace(/#/g, ".").replace(/o/g, "#")));

  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${G} ${G}`}
      shapeRendering="crispEdges"
      aria-hidden
      style={{ flexShrink: 0 }}
    >
      <path d={ring} fill="var(--accent)" />
      <path d={water} fill="var(--accent)" opacity="0.55" />
    </svg>
  );
}
